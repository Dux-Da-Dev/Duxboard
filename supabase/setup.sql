-- Function to get the role of the currently authenticated user
CREATE OR REPLACE FUNCTION get_user_role()
RETURNS TEXT AS $$
BEGIN
  RETURN (
    SELECT role
    FROM public.profiles
    WHERE id = auth.uid()
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to check if the currently authenticated user is an admin.
-- Using a SECURITY DEFINER function is more performant than per-row subqueries in RLS policies.
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1
    FROM public.profiles
    WHERE id = auth.uid() AND role = 'admin'
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to create a profile for a new user automatically
-- and assign 'admin' role to the first user.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
  is_first_user BOOLEAN;
  -- Define the default instruction templates
    instagram_instructions TEXT := 'A photorealistic and visually stunning image of [SUBJECT]. The style is minimalist and educational, with dramatic, high-contrast lighting and a clean, focused composition. The image must be a 1080x1350px vertical portrait.';

    tiktok_instructions TEXT := 'An energetic and vibrant vertical image of [SUBJECT], suitable for TikTok. The style is bold with a clear focal point, high-contrast colors, and dynamic lighting. The image must be in a 9:16 vertical format (1080x1920px).';
BEGIN
  -- Create the user''s public profile
  INSERT INTO public.profiles (id, full_name, avatar_url, role, theme)
  VALUES (NEW.id, NEW.raw_user_meta_data->>''full_name'', NEW.raw_user_meta_data->>''avatar_url'', ''user'', ''light'');

  -- Insert the default Instagram instruction profile for the new user
  INSERT INTO public.model_instructions (user_id, profile_name, instructions)
  VALUES (NEW.id, 'Instagram Image Default', instagram_instructions);

  -- Insert the default TikTok instruction profile for the new user
  INSERT INTO public.model_instructions (user_id, profile_name, instructions)
  VALUES (NEW.id, 'Tiktok Image Default', tiktok_instructions);

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to increment a user's image generation count
-- Function to increment a user's image generation count, excluding admin users.
CREATE OR REPLACE FUNCTION public.increment_image_count(user_id_param uuid)
RETURNS void AS $$
  UPDATE public.profiles
  SET image_generations_count = image_generations_count + 1
  WHERE id = user_id_param AND (SELECT role FROM public.profiles WHERE id = user_id_param) != 'admin';
$$ LANGUAGE sql;

-- Function to increment a user's text generation count, excluding admin users.
CREATE OR REPLACE FUNCTION public.increment_text_count(user_id_param uuid)
RETURNS void AS $$
  UPDATE public.profiles
  SET text_generations_count = text_generations_count + 1
  WHERE id = user_id_param AND (SELECT role FROM public.profiles WHERE id = user_id_param) != 'admin';
$$ LANGUAGE sql;

-- Function to increment a user's upload count, excluding admin users.
CREATE OR REPLACE FUNCTION public.increment_uploads_count(user_id_param uuid)
RETURNS void AS $$
  UPDATE public.profiles
  SET uploads_count = uploads_count + 1
  WHERE id = user_id_param AND (SELECT role FROM public.profiles WHERE id = user_id_param) != 'admin';
$$ LANGUAGE sql;


-- Trigger to execute the function after a new user is created
-- Drop trigger if it exists to make the script idempotent
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

