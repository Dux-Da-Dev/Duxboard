-- Policies for: storage.objects (bucket: images)
drop policy if exists "Images are publicly viewable" on storage.objects;
create policy "Images are publicly viewable" on storage.objects for select using ( bucket_id = 'images' );

drop policy if exists "Authenticated users can upload images" on storage.objects;
create policy "Authenticated users can upload images" on storage.objects for insert with check ( bucket_id = 'images' and auth.role() = 'authenticated' );

drop policy if exists "Users can update their own images" on storage.objects;
create policy "Users can update their own images" on storage.objects for update using ( auth.uid() = owner and bucket_id = 'images' );

drop policy if exists "Users can delete their own images" on storage.objects;
create policy "Users can delete their own images" on storage.objects for delete using ( auth.uid() = owner and bucket_id = 'images' );

-- Policies for: storage.objects (bucket: documents)
drop policy if exists "Users can view documents for accessible pins" on storage.objects;
create policy "Users can view documents for accessible pins" on storage.objects for select using (bucket_id = 'documents' and exists (select 1 from public.files where files.storage_path = storage.objects.name and exists (select 1 from public.pins where pins.id = files.pin_id)));

drop policy if exists "Authenticated users can upload documents" on storage.objects;
create policy "Authenticated users can upload documents" on storage.objects for insert with check ( bucket_id = 'documents' and auth.role() = 'authenticated' );

drop policy if exists "Users can update their own documents" on storage.objects;
create policy "Users can update their own documents" on storage.objects for update using ( auth.uid() = owner and bucket_id = 'documents' );

drop policy if exists "Users can delete their own documents" on storage.objects;
create policy "Users can delete their own documents" on storage.objects for delete using ( auth.uid() = owner and bucket_id = 'documents' );

-- Create generation_jobs table
CREATE TABLE IF NOT EXISTS public.generation_jobs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    anchor_pin_id UUID REFERENCES public.pins(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending', -- pending, processing, completed, failed
    job_type TEXT NOT NULL, -- 'ai_prompt' or 'url'
    source_content TEXT NOT NULL, -- The AI prompt or the image URL
    note_text TEXT,
    pin_position JSONB,
    related_instruction_id UUID REFERENCES public.model_instructions(id),
    error_message TEXT
);

-- Enable RLS for the new table
ALTER TABLE public.generation_jobs ENABLE ROW LEVEL SECURITY;

-- Policies for: public.generation_jobs
CREATE POLICY "Users can manage their own generation jobs"
ON public.generation_jobs
FOR ALL
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);
