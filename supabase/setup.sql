-- This script provides a consolidated, idempotent setup for the entire
-- Project Canvas database schema, including tables, roles, policies,
-- and storage. Running this script on a fresh Supabase project will
-- configure it completely.

-- =================================================================
-- Table Definitions
-- =================================================================

-- Create profiles table
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade not null primary key,
  full_name text,
  avatar_url text,
  role text default 'user',
  theme text default 'light',
  image_generations_count integer not null default 0,
  text_generations_count integer not null default 0,
  uploads_count integer not null default 0
);
comment on table public.profiles is 'Public user profiles, linked to auth.users.';
comment on column public.profiles.id is 'References auth.users.id';
comment on column public.profiles.role is 'User role, e.g., ''admin'' or ''user''';
comment on column public.profiles.theme is 'User preferred theme, e.g., ''light'' or ''dark''';

-- Create pins table
create table if not exists public.pins (
  id uuid primary key default gen_random_uuid(),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  user_id uuid references auth.users on delete cascade not null,
  image_url text not null,
  position jsonb not null default '{"x": 0, "y": 0}',
  notes text,
  is_deleted boolean default false not null
);
comment on table public.pins is 'Stores all the pins for the pinboard.';
comment on column public.pins.position is 'Stores the {x, y} coordinates of the pin.';

-- Create files table
create table if not exists public.files (
  id uuid primary key default gen_random_uuid(),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  pin_id uuid references public.pins on delete cascade not null,
  user_id uuid references auth.users on delete cascade not null,
  file_name text not null,
  storage_path text not null
);
comment on table public.files is 'Stores metadata for files attached to pins.';

-- Create connections table
create table if not exists public.connections (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    start_pin_id UUID REFERENCES public.pins(id) ON DELETE CASCADE NOT NULL,
    end_pin_id UUID REFERENCES public.pins(id) ON DELETE CASCADE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);
comment on table public.connections is 'Stores connections (lines) between pins.';

-- Create storylines table
create table if not exists public.storylines (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    title TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);
comment on table public.storylines is 'Stores storyline narratives created by users.';

-- Create storyline_pins joining table
create table if not exists public.storyline_pins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storyline_id uuid REFERENCES public.storylines(id) ON DELETE CASCADE NOT NULL,
    pin_id uuid REFERENCES public.pins(id) ON DELETE CASCADE NOT NULL,
    is_completed BOOLEAN DEFAULT FALSE NOT NULL,
    position JSONB NOT NULL DEFAULT '{"x": 0, "y": 0}'
);
comment on table public.storyline_pins is 'Joins pins to storylines, defining their position and completion status.';
comment on column public.storyline_pins.position is 'Stores the {x, y} coordinates of the pin within the storyline canvas.';

